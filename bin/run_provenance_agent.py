#!/usr/bin/env python3
"""Prepare and verify reproducibility metadata for a Nextflow run."""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import io
import json
import pathlib
import subprocess
import sys
import tarfile
from typing import Any


def command(
    *args: str,
    cwd: pathlib.Path | None = None,
    timeout: int = 30,
    binary: bool = False,
) -> str | bytes:
    output = subprocess.check_output(
        args,
        cwd=cwd,
        text=not binary,
        stderr=subprocess.DEVNULL,
        timeout=timeout,
    )
    return output if binary else output.strip()


def git(repo: pathlib.Path, *args: str, binary: bool = False) -> str | bytes:
    return command("git", *args, cwd=repo, binary=binary)


def sha256_bytes(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def sha256_file(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def file_record(path: pathlib.Path) -> dict[str, Any]:
    resolved = path.expanduser().resolve()
    result: dict[str, Any] = {"path": str(resolved), "exists": resolved.exists()}
    if resolved.is_file():
        stat = resolved.stat()
        result.update(
            {
                "size_bytes": stat.st_size,
                "sha256": sha256_file(resolved),
                "modified_at_utc": dt.datetime.fromtimestamp(
                    stat.st_mtime, dt.timezone.utc
                ).isoformat(),
            }
        )
    return result


def commit_files(repo: pathlib.Path, commit: str) -> dict[str, str]:
    archive = git(repo, "archive", "--format=tar", commit, binary=True)
    assert isinstance(archive, bytes)
    hashes: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as handle:
        for member in handle.getmembers():
            if not member.isfile():
                continue
            extracted = handle.extractfile(member)
            if extracted is not None:
                hashes[member.name] = sha256_bytes(extracted.read())
    return hashes


def source_comparison(
    source_dir: pathlib.Path, expected: dict[str, str]
) -> tuple[list[str], str, list[str], list[str]]:
    lines: list[str] = []
    missing: list[str] = []
    mismatched: list[str] = []
    for relative, expected_hash in sorted(expected.items()):
        path = source_dir / relative
        if not path.is_file():
            missing.append(relative)
            lines.append(f"MISSING  {relative}")
            continue
        observed_hash = sha256_file(path)
        if observed_hash != expected_hash:
            mismatched.append(relative)
        lines.append(f"{observed_hash}  {relative}")
    text = "\n".join(lines) + "\n"
    return lines, text, missing, mismatched


def remote_head(repo_url: str, branch: str | None) -> tuple[str | None, str | None]:
    if not branch:
        return None, None
    try:
        line = command(
            "git", "ls-remote", repo_url, f"refs/heads/{branch}", timeout=20
        )
        assert isinstance(line, str)
        return (line.split()[0] if line else None), None
    except Exception as exc:
        return None, type(exc).__name__


def nextflow_version() -> str | None:
    try:
        output = command("nextflow", "-version")
        assert isinstance(output, str)
        for line in output.splitlines():
            if "version " in line:
                return line.strip()
    except Exception:
        pass
    return None


def safe_config_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def write_generated_config(
    path: pathlib.Path,
    repository_url: str,
    branch: str | None,
    commit: str,
    source_manifest_sha256: str,
    metadata_path: pathlib.Path,
) -> None:
    description = (
        f"Git commit {commit}; source manifest SHA-256 "
        f"{source_manifest_sha256}; metadata {metadata_path}"
    )
    content = f"""// Generated by bin/run_provenance_agent.py. Do not edit by hand.
manifest {{
    name = 'pinellolab/CRISPR_Pipeline'
    homePage = '{safe_config_string(repository_url)}'
    defaultBranch = '{safe_config_string(branch or "dev")}'
    version = '{commit[:12]}'
    description = '{safe_config_string(description)}'
}}
"""
    path.write_text(content)


def artifact_records(items: list[str]) -> dict[str, dict[str, Any]]:
    records: dict[str, dict[str, Any]] = {}
    for item in items:
        name, separator, raw_path = item.partition("=")
        if not separator or not name or not raw_path:
            raise ValueError(f"Invalid artifact, expected NAME=PATH: {item!r}")
        if name in records:
            raise ValueError(f"Duplicate artifact name: {name}")
        records[name] = file_record(pathlib.Path(raw_path))
    return records


def prepare(args: argparse.Namespace) -> int:
    repo = args.pipeline_repo.expanduser().resolve()
    source = (args.source_dir or repo).expanduser().resolve()
    output = args.output_dir.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)

    commit_raw = git(repo, "rev-parse", f"{args.expected_commit}^{{commit}}")
    assert isinstance(commit_raw, str)
    commit = commit_raw
    head_raw = git(repo, "rev-parse", "HEAD")
    assert isinstance(head_raw, str)
    status_raw = git(repo, "status", "--porcelain=v1")
    assert isinstance(status_raw, str)
    try:
        branch_raw = git(repo, "symbolic-ref", "--short", "-q", "HEAD")
        assert isinstance(branch_raw, str)
        branch = branch_raw or None
    except subprocess.CalledProcessError:
        branch = None
    repo_url_raw = git(repo, "remote", "get-url", "origin")
    assert isinstance(repo_url_raw, str)
    repo_url = repo_url_raw
    metadata_raw = git(
        repo, "show", "-s", "--format=%H%x00%h%x00%aI%x00%an%x00%s", commit
    )
    assert isinstance(metadata_raw, str)
    commit_metadata = metadata_raw.split("\0")

    expected = commit_files(repo, commit)
    lines, manifest_text, missing, mismatched = source_comparison(source, expected)
    source_manifest_sha256 = sha256_bytes(manifest_text.encode())
    current_remote_head, remote_error = remote_head(repo_url, branch)
    matches_commit = not missing and not mismatched
    dirty = bool(status_raw)

    errors: list[str] = []
    if not matches_commit and not args.allow_source_mismatch:
        errors.append(
            f"executing source does not match commit {commit}: "
            f"{len(missing)} missing, {len(mismatched)} mismatched"
        )
    if source == repo and dirty and not args.allow_dirty:
        errors.append(
            "the executing repository checkout is dirty; commit provenance "
            "would be incomplete"
        )
    if args.require_remote_head and commit != current_remote_head:
        errors.append(
            f"commit {commit} is not current origin/{branch} head "
            f"({current_remote_head or 'unavailable'})"
        )
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 2

    manifest_path = output / "pipeline_source_files.sha256"
    manifest_path.write_text(manifest_text)
    json_path = output / "repository_provenance.json"
    tsv_path = output / "repository_provenance.tsv"
    generated_config = output / "provenance.generated.config"

    provenance: dict[str, Any] = {
        "schema_version": 1,
        "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "run": {
            "name": args.run_name,
            "nextflow_script_revision": args.nextflow_revision,
            "tower_workflow_id": args.tower_workflow_id,
            "tower_url": args.tower_url,
        },
        "pipeline_source": {
            "repository_path": str(repo),
            "repository_url": repo_url,
            "branch": branch,
            "repository_head": head_raw,
            "repository_dirty": dirty,
            "repository_status_porcelain": status_raw.splitlines(),
            "expected_commit": commit_metadata[0],
            "expected_commit_short": commit_metadata[1],
            "commit_date": commit_metadata[2],
            "commit_author": commit_metadata[3],
            "commit_subject": commit_metadata[4],
            "remote_branch_head": current_remote_head,
            "remote_head_check_error": remote_error,
            "commit_is_current_remote_branch_head": (
                commit == current_remote_head if current_remote_head else None
            ),
            "executed_source_directory": str(source),
            "git_commit_file_count": len(lines),
            "source_manifest_sha256": source_manifest_sha256,
            "source_matches_expected_commit": matches_commit,
            "missing_commit_files": missing,
            "mismatched_commit_files": mismatched,
            "manifest_path": str(manifest_path),
        },
        "software": {"nextflow_version": nextflow_version()},
        "launch_artifacts": artifact_records(args.artifact),
        "generated_nextflow_config": str(generated_config),
    }
    json_path.write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n")
    write_generated_config(
        generated_config,
        repo_url,
        branch,
        commit,
        source_manifest_sha256,
        json_path,
    )

    flat = [
        ("generated_at_utc", provenance["generated_at_utc"]),
        ("run_name", args.run_name),
        ("nextflow_script_revision", args.nextflow_revision or ""),
        ("tower_workflow_id", args.tower_workflow_id or ""),
        ("repository_url", repo_url),
        ("branch", branch or ""),
        ("expected_commit", commit),
        ("repository_head", head_raw),
        ("repository_dirty", str(dirty).lower()),
        ("remote_branch_head", current_remote_head or ""),
        (
            "commit_is_current_remote_branch_head",
            str(commit == current_remote_head).lower() if current_remote_head else "",
        ),
        ("source_manifest_sha256", source_manifest_sha256),
        ("source_matches_expected_commit", str(matches_commit).lower()),
        ("nextflow_version", provenance["software"]["nextflow_version"] or ""),
        ("generated_nextflow_config", str(generated_config)),
    ]
    tsv_path.write_text(
        "field\tvalue\n" + "".join(f"{key}\t{value}\n" for key, value in flat)
    )

    print(json_path)
    print(tsv_path)
    print(manifest_path)
    print(generated_config)
    return 0


def check(args: argparse.Namespace) -> int:
    metadata_path = args.metadata.expanduser().resolve()
    data = json.loads(metadata_path.read_text())
    source_info = data["pipeline_source"]
    repo = args.pipeline_repo.expanduser().resolve()
    source = pathlib.Path(source_info["executed_source_directory"])
    commit = source_info["expected_commit"]

    expected = commit_files(repo, commit)
    _, manifest_text, missing, mismatched = source_comparison(source, expected)
    observed_manifest = sha256_bytes(manifest_text.encode())
    errors: list[str] = []
    if missing or mismatched:
        errors.append(
            f"source changed: {len(missing)} missing, {len(mismatched)} mismatched"
        )
    if observed_manifest != source_info["source_manifest_sha256"]:
        errors.append("source manifest SHA-256 no longer matches metadata")

    for name, record in data.get("launch_artifacts", {}).items():
        path = pathlib.Path(record["path"])
        if not path.is_file():
            errors.append(f"artifact {name} is missing: {path}")
        elif sha256_file(path) != record.get("sha256"):
            errors.append(f"artifact {name} changed: {path}")

    generated_config = pathlib.Path(data["generated_nextflow_config"])
    if not generated_config.is_file():
        errors.append(f"generated Nextflow config is missing: {generated_config}")

    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 2
    print(f"OK: provenance is current for {data['run']['name']}")
    print(generated_config)
    return 0


def parser() -> argparse.ArgumentParser:
    top = argparse.ArgumentParser()
    sub = top.add_subparsers(dest="mode", required=True)

    prepare_parser = sub.add_parser("prepare")
    prepare_parser.add_argument("--pipeline-repo", type=pathlib.Path, required=True)
    prepare_parser.add_argument("--source-dir", type=pathlib.Path)
    prepare_parser.add_argument("--output-dir", type=pathlib.Path, required=True)
    prepare_parser.add_argument("--run-name", required=True)
    prepare_parser.add_argument("--expected-commit", default="HEAD")
    prepare_parser.add_argument("--nextflow-revision")
    prepare_parser.add_argument("--tower-workflow-id")
    prepare_parser.add_argument("--tower-url")
    prepare_parser.add_argument(
        "--artifact", action="append", default=[], metavar="NAME=PATH"
    )
    prepare_parser.add_argument("--allow-dirty", action="store_true")
    prepare_parser.add_argument("--allow-source-mismatch", action="store_true")
    prepare_parser.add_argument("--require-remote-head", action="store_true")
    prepare_parser.set_defaults(handler=prepare)

    check_parser = sub.add_parser("check")
    check_parser.add_argument("--pipeline-repo", type=pathlib.Path, required=True)
    check_parser.add_argument("--metadata", type=pathlib.Path, required=True)
    check_parser.set_defaults(handler=check)
    return top


def main() -> int:
    args = parser().parse_args()
    try:
        return args.handler(args)
    except (OSError, subprocess.SubprocessError, ValueError, KeyError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
