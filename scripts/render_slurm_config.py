#!/usr/bin/env python3
"""Render the commented Slurm reference from active defaults and the schema."""

import argparse
import json
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "conf/simplified_pipeline/nextflow_slurm_all_options.config"
ASSIGNMENT = re.compile(r"^\s*(\w+)\s*=\s*(.*?)\s*$")
PARAM_BLOCK = re.compile(r"^params \{\n(.*?)^\}", re.M | re.S)
CONTAINER_BLOCK = re.compile(r"^    containers \{\n(.*?)^    \}", re.M | re.S)


def assignments(source):
    for line in source.splitlines():
        match = ASSIGNMENT.match(line)
        if not match:
            continue
        name, value = match.groups()
        # Inline config comments in the canonical file follow whitespace.
        yield name, re.split(r"\s+//", value, maxsplit=1)[0]


def render():
    config = (ROOT / "nextflow.config").read_text()
    manifest = (ROOT / "conf/provenance.config").read_text()
    version = re.search(r"^\s*version = '([^']+)'", manifest, re.M).group(1)
    schema = json.loads((ROOT / "nextflow_schema.json").read_text())
    blocks = PARAM_BLOCK.findall(config)
    all_blocks = "\n".join(blocks)
    containers = dict(assignments(CONTAINER_BLOCK.search(all_blocks).group(1)))
    defaults = dict(assignments(CONTAINER_BLOCK.sub("", all_blocks)))
    specs = {name: spec for group in schema["$defs"].values()
             for name, spec in group.get("properties", {}).items()}
    required = {name for group in schema["$defs"].values() for name in group.get("required", [])}
    seen = set()

    lines = [
        f"// CRISPR Pipeline v{version} · Slurm defaults and optional settings",
        "// Use with the pinned release: nextflow run main.nf -profile slurm -c nextflow_slurm_all_options.config",
        "// Add absolute --input and --outdir paths on the launch command.",
        "// Uncomment only intended overrides. The commented values show defaults from nextflow.config.",
        "// A schema-only setting is marked when the engine config has no assignment.",
        "// Generated by scripts/render_slurm_config.py. Edit the source defaults or descriptions to refresh this file.",
        "",
        "params {",
    ]

    def section(title):
        lines.extend(["", "    // ------------------------------------------------------------------", f"    // {title}",
                      "    // ------------------------------------------------------------------"])

    def parameter(name, spec=None, required=False):
        spec = spec or {}
        detail = spec.get("description", "")
        if required:
            detail = f"Required for a fresh samplesheet run. {detail}"
        if detail:
            lines.extend(textwrap.wrap(detail, width=96, initial_indent="    // ", subsequent_indent="    // "))
        if name in defaults:
            value = defaults[name]
        elif "default" in spec:
            value = json.dumps(spec["default"], ensure_ascii=False)
            lines.append("    // Schema default only. Review the specific module before overriding.")
        else:
            value = "null"
            lines.append("    // Optional. No configured or schema default.")
        lines.append(f"    // {name} = {value}")
        seen.add(name)

    section("1. Essential run settings")
    for name, _ in assignments(blocks[0]):
        parameter(name, specs.get(name), name in required)

    section("2. Advanced options")
    for key, group in schema["$defs"].items():
        remaining = [(name, spec) for name, spec in group.get("properties", {}).items() if name not in seen]
        if not remaining:
            continue
        section(group["title"])
        for name, spec in remaining:
            if key == "inference_options" and name == "INFERENCE_SCEPTRE_control_group":
                lines.extend(["", "    // SCEPTRE-specific inference controls"])
            if key == "inference_options" and name == "INFERENCE_PERTURBO_DEVICE":
                lines.extend(["", "    // PerTurbo-specific inference controls"])
            parameter(name, spec, name in group.get("required", []))

    section("Additional engine defaults and compatibility parameters")
    for name in defaults:
        if name not in seen:
            parameter(name)
    section("Container images")
    lines.append("    // containers {")
    lines.extend(f"    //     {name} = {value}" for name, value in containers.items())
    lines.extend(["    // }", "}", "", "// ----------------------------------------------------------------------",
                  "// Dashboard observer", "// ----------------------------------------------------------------------"])
    dashboard = (ROOT / "conf/dashboard_plugin.config").read_text().split("params.DASHBOARD_PLUGIN", 1)[1]
    lines.extend(f"// {line}" for line in ("params.DASHBOARD_PLUGIN" + dashboard).strip().splitlines())
    lines.extend([
        "",
        "// ----------------------------------------------------------------------",
        "// 3. Slurm site settings · set shared absolute paths and your scheduler partitions",
        "// ----------------------------------------------------------------------",
        "// profiles {",
        "//     slurm {",
        "//         process.queue = System.getenv('CRISPR_SLURM_QUEUE') ?: 'short,normal,long'",
        "//         workDir = System.getenv('CRISPR_NXF_WORK') ?: './work'",
        "//         executor.queueSize = 100",
        "//         executor.pollInterval = '30 sec'",
        "//         executor.submitRateLimit = '10 sec'",
        "//         singularity.cacheDir = System.getenv('CRISPR_SIF_CACHE') ?: './singularity-cache'",
        "//     }",
        "// }",
        "// Use the scheduler GPU partition/GRES only for an inference mode with GPU PerTurbo.",
        "// process {",
        "//     withName: 'inference_perturbo' {",
        "//         queue = System.getenv('CRISPR_SLURM_GPU_QUEUE')",
        "//         accelerator = null",
        "//         clusterOptions = '--gres=gpu:1'",
        "//         containerOptions = '--nv'",
        "//     }",
        "// }",
        "// Use either Singularity or Apptainer in this profile, according to site policy.",
        "// singularity.enabled = false",
        "// apptainer {",
        "//     enabled = true",
        "//     autoMounts = true",
        "//     cacheDir = System.getenv('CRISPR_SIF_CACHE') ?: './apptainer-cache'",
        "// }",
    ])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != rendered:
            parser.exit(1, f"{OUTPUT.relative_to(ROOT)} is stale. Run {Path(__file__).name}.\n")
    else:
        OUTPUT.write_text(rendered)


if __name__ == "__main__":
    main()
